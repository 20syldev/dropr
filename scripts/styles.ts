import fs from 'fs';
import { join } from 'path';

const ROOT = join(import.meta.dirname, '..');

const STRINGS = /('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")/;

/**
 * Reads the style sheets of a folder, one CSS file each, named after its order and its topic (1-theme.css).
 *
 * @param dir - Folder of the CSS files; other files are left alone
 * @returns The files joined in the order of their numbers, each one ending with a line break
 */
export function readStyles(dir: string): string {
    const found: { order: number; css: string }[] = [];

    for (const name of fs.readdirSync(dir).filter((file) => file.endsWith('.css'))) {
        const named = /^(\d+)-[a-z0-9]+(-[a-z0-9]+)*\.css$/.exec(name);
        if (!named) throw new Error(`${name} must start with a number and a dash, then lower case words`);
        const order = Number(named[1]);
        if (found.some((entry) => entry.order === order)) throw new Error(`number ${order} is used twice`);

        const css = fs.readFileSync(join(dir, name), 'utf-8');

        found.push({ order, css: css.endsWith('\n') ? css : `${css}\n` });
    }

    return found
        .sort((a, b) => a.order - b.order)
        .map(({ css }) => css)
        .join('');
}

/**
 * Removes what a browser does not need between the tokens of a piece of CSS that holds no string.
 *
 * @param part - CSS outside of any string
 * @returns The CSS without line breaks, and without spaces around braces, semicolons, commas and colons
 */
function squeeze(part: string): string {
    return part
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/\s+/g, ' ')
        .replace(/ ?([{};,]) ?/g, '$1')
        .replace(/: /g, ':')
        .replace(/;}/g, '}');
}

/**
 * Makes a style sheet smaller without changing a rule.
 *
 * It drops the comments and the white space around the tokens that do not need it; a string is left as written.
 *
 * @param css - Style sheet
 * @returns The same rules on one line
 */
export function minify(css: string): string {
    return css
        .split(STRINGS)
        .map((part, n) => (n % 2 === 1 ? part : squeeze(part)))
        .join('')
        .trim();
}

/**
 * Writes the module that holds the style sheet, a line of CSS on a line of the file so that a change of the sheet reads
 * as such in a diff when it is not minified.
 *
 * @param css - Style sheet, minified or not
 * @returns The source of src/core/pages/style.ts
 */
export function render(css: string): string {
    return [
        '// Generated by scripts/styles.ts from styles/*.css, do not edit it: run npm run styles',
        'export const STYLE = [',
        ...css.split('\n').map((line) => `    ${JSON.stringify(line)},`),
        "].join('\\n');",
        '',
    ].join('\n');
}

if (process.argv[1] === import.meta.filename) {
    const css = readStyles(join(ROOT, 'src', 'core', 'pages', 'styles'));

    fs.writeFileSync(
        join(ROOT, 'src', 'core', 'pages', 'style.ts'),
        render(process.argv.includes('--minify') ? minify(css) : css),
    );
}
