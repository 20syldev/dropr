import fs from 'fs';
import { join } from 'path';

/**
 * One page of the docs, as the pages of the server hold it.
 */
export interface Guide {
    slug: string;
    title: string;
    markdown: string;
}

const ROOT = join(import.meta.dirname, '..');

/**
 * Finds the first heading of level one that is not inside a fenced code block.
 *
 * @param markdown - Text of a guide
 * @returns The text of the heading, or undefined when the guide has none
 */
function titleOf(markdown: string): string | undefined {
    let fence: string | null = null;

    for (const line of markdown.split('\n')) {
        const opening = /^ {0,3}(`{3,}|~{3,})/.exec(line)?.[1];

        if (fence === null) {
            if (opening) fence = opening;
            else if (line.startsWith('# ') && line.slice(2).trim()) return line.slice(2).trim();
        } else if (opening && opening[0] === fence[0] && opening.length >= fence.length) {
            fence = null;
        }
    }
}

/**
 * Reads the guides of a folder, one Markdown file each, named after its number and its slug (1-overview.md).
 *
 * @param dir - Folder of the Markdown files; other files are left alone
 * @returns The guides in the order of their numbers, the title being the first heading of level one
 */
export function readGuides(dir: string): Guide[] {
    const found: { order: number; guide: Guide }[] = [];

    for (const name of fs.readdirSync(dir).filter((file) => file.endsWith('.md'))) {
        const named = /^(\d+)-(.+)\.md$/.exec(name);
        if (!named) throw new Error(`${name} must start with a number and a dash`);
        const order = Number(named[1]);
        const slug = named[2];
        if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) {
            throw new Error(`${name}: the slug must be lower case words joined by dashes`);
        }
        if (found.some((entry) => entry.guide.slug === slug)) throw new Error(`slug ${slug} is used twice`);
        if (found.some((entry) => entry.order === order)) throw new Error(`number ${order} is used twice`);

        const markdown = fs.readFileSync(join(dir, name), 'utf-8');
        const title = titleOf(markdown);
        if (!title) throw new Error(`${name} has no title: start a line with "# "`);

        found.push({ order, guide: { slug, title, markdown } });
    }

    return found.sort((a, b) => a.order - b.order).map(({ guide }) => guide);
}

/**
 * Writes the module that holds the guides, a line of Markdown on a line of the file so that a change of the docs reads
 * as such in a diff, and so that no text can start a line with import or export.
 *
 * @param guides - Guides in the order of the docs
 * @returns The source of src/lib/guides.ts
 */
export function render(guides: Guide[]): string {
    const entries = guides.flatMap(({ slug, title, markdown }) => [
        '    {',
        `        slug: ${JSON.stringify(slug)},`,
        `        title: ${JSON.stringify(title)},`,
        '        markdown: [',
        ...markdown.split('\n').map((line) => `            ${JSON.stringify(line)},`),
        "        ].join('\\n'),",
        '    },',
    ]);

    return [
        '// Generated by scripts/docs.ts from docs/*.md, do not edit it: run npm run docs',
        "import type { Guide } from '../types/index.js';",
        '',
        'export const GUIDES: Guide[] = [',
        ...entries,
        '];',
        '',
    ].join('\n');
}

if (process.argv[1] === import.meta.filename) {
    fs.writeFileSync(join(ROOT, 'src', 'lib', 'guides.ts'), render(readGuides(join(ROOT, 'docs'))));
}
