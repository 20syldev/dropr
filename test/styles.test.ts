import assert from 'assert/strict';
import fs from 'fs';
import { after, describe, test } from 'node:test';
import os from 'os';
import { join } from 'path';

import { STYLE } from '../dist/core/pages/style.js';
import { minify, readStyles, render } from '../scripts/styles.ts';

import { rootDir } from './server.ts';

/**
 * Takes away what minify may remove, so that two sheets can be compared by their rules alone.
 *
 * @param css - Style sheet
 * @returns The sheet without white space nor the semicolon that ends a block
 */
function skeleton(css: string): string {
    return css.replace(/\s+/g, '').replace(/;}/g, '}');
}

describe('readStyles', () => {
    const folders: string[] = [];
    const open = (files: Record<string, string>): string => {
        const dir = fs.mkdtempSync(join(os.tmpdir(), 'dropr-styles-'));
        for (const [name, text] of Object.entries(files)) fs.writeFileSync(join(dir, name), text);
        folders.push(dir);

        return dir;
    };

    after(() => {
        for (const dir of folders) {
            for (const name of fs.readdirSync(dir)) fs.unlinkSync(join(dir, name));
            fs.rmdirSync(dir);
        }
    });

    test('joins the files in the order of their number and ends each one with a line break', () => {
        const dir = open({
            '10-last.css': 'c { top: 0; }',
            '2-middle.css': 'b { top: 0; }\n',
            '1-first.css': 'a { top: 0; }\n',
            'notes.txt': 'not a style',
        });

        assert.equal(readStyles(dir), 'a { top: 0; }\nb { top: 0; }\nc { top: 0; }\n');
    });

    test('refuses a name without a number, a name that is not lower case words and a number used twice', () => {
        assert.throws(() => readStyles(open({ 'base.css': '' })), /base\.css must start with a number/);
        assert.throws(() => readStyles(open({ '1-Base.css': '' })), /1-Base\.css must start with a number/);
        assert.throws(() => readStyles(open({ '1-a.css': '', '01-b.css': '' })), /number 1 is used twice/);
    });
});

describe('minify', () => {
    test('drops the comments, the line breaks and the spaces around braces, semicolons, commas and colons', () => {
        const css = '/* note */\na,\nb {\n    color: red;\n    margin: 0 auto;\n}\n';

        assert.equal(minify(css), 'a,b{color:red;margin:0 auto}');
    });

    test('keeps the space of a descendant selector, of a media query, of a calculation and of an important mark', () => {
        assert.equal(minify('.a .b > c:hover { width: calc(1px + 2px); }'), '.a .b > c:hover{width:calc(1px + 2px)}');
        assert.equal(
            minify('@media (max-width: 40rem) and (hover: hover) { a { top: 0 } }'),
            '@media (max-width:40rem) and (hover:hover){a{top:0}}',
        );
        assert.equal(minify('a { top: 0 !important; }'), 'a{top:0 !important}');
    });

    test('leaves a string as it is, braces, commas and spaces included', () => {
        assert.equal(minify("a::before { content: ' { ,  : ; } '; }"), "a::before{content:' { ,  : ; } '}");
        assert.equal(
            minify('a::after { content: "x ;  y"; font-family: \'A B\', "C D"; }'),
            'a::after{content:"x ;  y";font-family:\'A B\',"C D"}',
        );
        assert.equal(minify("a { content: 'it\\'s  here'; }"), "a{content:'it\\'s  here'}");
    });

    test('changes nothing but white space and comments in the style sheet of the pages', () => {
        const small = minify(STYLE);

        assert.ok(small.length < STYLE.length);
        assert.ok(!small.includes('\n'));
        assert.equal(skeleton(small), skeleton(STYLE));
        assert.equal(small.split('{').length, small.split('}').length);
        assert.equal(minify(small), small);
    });
});

describe('render', () => {
    test('writes a module whose constant holds the sheet, a line of CSS on a line of the file', () => {
        const text = render('a { top: 0; }\nb { top: 1; }\n');

        assert.equal(
            text,
            [
                '// Generated by scripts/styles.ts from styles/*.css, do not edit it: run npm run styles',
                'export const STYLE = [',
                '    "a { top: 0; }",',
                '    "b { top: 1; }",',
                '    "",',
                "].join('\\n');",
                '',
            ].join('\n'),
        );
    });

    test('writes a minified sheet on one line', () => {
        assert.match(render('a{top:0}'), /export const STYLE = \[\n {4}"a\{top:0\}",\n\]\.join\('\\n'\);\n$/);
    });
});

describe('the style sheet of dropr', () => {
    test('is the one written in src/core/pages/styles, as the generated module holds it', () => {
        assert.equal(STYLE, readStyles(join(rootDir, 'src', 'core', 'pages', 'styles')));
    });
});
